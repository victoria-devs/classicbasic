    println!("[Test 1] VarSub (40 - 2): {}", bstr_to_string(b_sub));
    SysFreeString(b_add);
    SysFreeString(b_sub);

    // [Test 2] VarMul (25 * 4): 100
    // [Test 2] VarDiv (25 / 4): 6.25
    // [Test 2] VarIdiv (25 \ 4): 6
    // [Test 2] VarMod (25 Mod 4): 1
