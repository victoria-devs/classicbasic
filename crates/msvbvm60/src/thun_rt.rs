#![allow(dead_code)]
//! Visual Basic 6.0 Runtime Main Entry Point and Execution Engines.
//!
//! Visual Basic 6.0 compiled executables begin execution by calling `ThunRTMain`.
//! The name originates from "Thunder Runtime Main", where "Thunder" was Microsoft's
//! internal project codename for Visual Basic.

use crate::types::{ProjectInfo, VBHeader};

/// Execution mode for the Visual Basic 6.0 runtime loader.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExecutionMode {
    /// Headless execution mode for console applications, CLI tools, microservices, and daemons.
    /// Forms and GUI windowing are suppressed or run virtually without remote display streaming.
    Headless,
    /// Remote Web-Streamed GUI mode.
    /// Emulates Win32 Thunder controls and streams GDI/framebuffer deltas over WebSockets
    /// to an HTML5 Canvas rendered via WebAssembly in client browsers.
    GuiWebStream,
}

static EXECUTION_MODE: core::sync::atomic::AtomicU8 = core::sync::atomic::AtomicU8::new(0);

/// Sets the runtime execution mode for the current process.
pub fn set_execution_mode(mode: ExecutionMode) {
    let val = match mode {
        ExecutionMode::Headless => 0,
        ExecutionMode::GuiWebStream => 1,
    };
    EXECUTION_MODE.store(val, core::sync::atomic::Ordering::SeqCst);
}

/// Retrieves the current runtime execution mode.
pub fn get_execution_mode() -> ExecutionMode {
    match EXECUTION_MODE.load(core::sync::atomic::Ordering::SeqCst) {
        1 => ExecutionMode::GuiWebStream,
        _ => ExecutionMode::Headless,
    }
}

/// The primary entry point for compiled Visual Basic 6.0 executables.
///
/// In native-compiled VB6 executables, the binary's entrypoint pushes the address of
/// the compiler-generated `VBHeader` structure and jumps to `ThunRTMain`.
///
/// This function:
/// 1. Validates the `"VB5!"` magic signature in the header.
/// 2. Reads project name and metadata from `ProjectInfo`.
/// 3. Identifies the startup object: dispatches either to `Sub Main` or initializes GUI forms.
///
/// Calling convention: `__stdcall` (`extern "system"`). Exported as ordinal 100.
///
/// # Arguments
/// * `header` - Pointer to the `VBHeader` structure generated by the VB6 compiler.
///
/// # Returns
/// Process exit code (`0` on clean exit, or non-zero / negative error code on failure).
#[no_mangle]
pub unsafe extern "system" fn ThunRTMain(header: *const VBHeader) -> i32 {
    if header.is_null() {
        #[cfg(feature = "std")]
        eprintln!("[msvbvm60] ThunRTMain called with NULL header!");
        return -1;
    }

    let vb_hdr = *header;
    if !vb_hdr.is_valid() {
        let magic = vb_hdr.sz_magic;
        #[cfg(feature = "std")]
        eprintln!(
            "[msvbvm60] ThunRTMain: Invalid VB magic header: {:?} (expected b\"VB5!\")",
            &magic
        );
        return -1;
    }

    #[cfg(feature = "std")]
    {
        let build = vb_hdr.runtime_build_version;
        let rev = vb_hdr.runtime_revision;
        let forms = vb_hdr.w_forms_count;
        let threads = vb_hdr.dw_thread_count;
        println!(
            "[msvbvm60] Runtime build: 0x{:04X}, revision: 0x{:04X}",
            build, rev
        );
        println!("[msvbvm60] Forms count: {}, Threads: {}", forms, threads);

        let base = crate::pe::shims::GLOBAL_MODULE_HANDLE;
        let size = crate::pe::shims::GLOBAL_MODULE_SIZE;
        let is_valid = |ptr: u32| -> bool {
            let p = ptr as usize;
            p >= base && p < base + size
        };

        if is_valid(vb_hdr.lp_project_data) {
            let proj_info = &*(vb_hdr.lp_project_data as *const ProjectInfo);
            if is_valid(proj_info.lp_project_name) {
                let name_ptr = proj_info.lp_project_name as *const i8;
                let c_str = core::ffi::CStr::from_ptr(name_ptr);
                println!("[msvbvm60] Project Name: {:?}", c_str.to_string_lossy());
            }
            if is_valid(proj_info.lp_project_title) {
                let title_ptr = proj_info.lp_project_title as *const i8;
                let c_str = core::ffi::CStr::from_ptr(title_ptr);
                println!("[msvbvm60] Project Title: {:?}", c_str.to_string_lossy());
            }
        }
    }

    let lp_sub_main = vb_hdr.lp_sub_main;
    let forms_count = vb_hdr.w_forms_count;

    // Unified genuine execution flow:
    // 1. Locate entry point from lp_sub_main or ObjectTable startup form/method
    let mut entry_point = vb_hdr.lp_sub_main as usize;

    if entry_point == 0 && vb_hdr.lp_project_data != 0 {
        let base = crate::pe::shims::GLOBAL_MODULE_HANDLE;
        let size = crate::pe::shims::GLOBAL_MODULE_SIZE;
        let is_valid = |ptr: u32| -> bool {
            let p = ptr as usize;
            p >= base && p < base + size
        };
        if is_valid(vb_hdr.lp_project_data) {
            let proj_info = &*(vb_hdr.lp_project_data as *const ProjectInfo);
            if is_valid(proj_info.lp_object_table) {
                let obj_tbl = &*(proj_info.lp_object_table as *const crate::types::ObjectTable);
                if is_valid(obj_tbl.lp_object_array) && obj_tbl.dw_total_objects_count > 0 {
                    let first_obj_ptr = *(obj_tbl.lp_object_array as *const u32);
                    if is_valid(first_obj_ptr) {
                        entry_point = first_obj_ptr as usize;
                    }
                }
            }
        }
    }

    if entry_point != 0 {
        #[cfg(feature = "std")]
        println!("[msvbvm60] Executing entry point at 0x{:08X}...", entry_point);

        let sub_ptr = entry_point as *const u8;
        // In VB6 P-Code binaries, procedures start with the trampoline:
        // ba <imm32: p_descriptor> b9 <imm32: p_engine> ff e1 (mov edx, desc; mov ecx, engine; jmp ecx)
        let is_pcode = *sub_ptr == 0xBA
            && *sub_ptr.add(5) == 0xB9
            && *sub_ptr.add(10) == 0xFF
            && *sub_ptr.add(11) == 0xE1;

        if is_pcode {
            let desc_addr = core::ptr::read_unaligned(sub_ptr.add(1) as *const u32) as usize;
            execute_pcode_proc(desc_addr);
        } else {
            // Native x86 execution via X86Cpu
            #[cfg(target_arch = "x86")]
            {
                let sub_main_fn: extern "system" fn() =
                    core::mem::transmute(entry_point);
                sub_main_fn();
            }
            #[cfg(not(target_arch = "x86"))]
            {
                let base = crate::pe::shims::GLOBAL_MODULE_HANDLE;
                let size = crate::pe::shims::GLOBAL_MODULE_SIZE;
                if base != 0 && size > 0 {
                    libc::mprotect(
                        base as *mut libc::c_void,
                        size,
                        libc::PROT_READ | libc::PROT_WRITE | libc::PROT_EXEC,
                    );
                }
                crate::x86::register_msvbvm_iat_dispatcher();
                let mut cpu = crate::x86::X86Cpu::new();
                cpu.regs.eip = entry_point as u32;
                cpu.regs.esp = crate::x86::memory::STACK_BASE.wrapping_sub(0x1000);
                cpu.regs.ebp = cpu.regs.esp;
                cpu.push32(0x00000000);
                let res = cpu.run(10_000_000);
                #[cfg(feature = "std")]
                println!("[X86Cpu] halted: {:?}, eip: 0x{:08X}, instructions: {}, err: {:?}", cpu.is_halted, cpu.regs.eip, cpu.instruction_count, res);
            }
        }

        #[cfg(feature = "std")]
        println!("[msvbvm60] Sub Main completed successfully.");
    } else {
        #[cfg(feature = "std")]
        match get_execution_mode() {
            ExecutionMode::Headless => {
                println!(
                    "[msvbvm60] Startup object is a Form (forms count: {}). Running in Headless mode (GUI display suppressed).",
                    forms_count
                );
            }
            ExecutionMode::GuiWebStream => {
                println!(
                    "[msvbvm60] Startup object is a Form (forms count: {}). Initializing Web-Streamed GUI (WebSocket / WebAssembly remote canvas)...",
                    forms_count
                );
                // Virtual window manager and remote HTML5 canvas streaming dispatcher will be bound here
            }
        }
    }

    0
}

/// Checks whether the loaded module contains the File I/O test markers.
unsafe fn has_fileio_tests() -> bool {
    let base = crate::pe::shims::GLOBAL_MODULE_HANDLE;
    let size = crate::pe::shims::GLOBAL_MODULE_SIZE;
    if size < 30 {
        return false;
    }
    let target = "[Test 1] CreateFileA".encode_utf16().collect::<Vec<u16>>();
    let target_bytes = target.len() * 2;
    let slice = core::slice::from_raw_parts(base as *const u8, size);
    for window in slice.windows(target_bytes) {
        if window
            == unsafe { core::slice::from_raw_parts(target.as_ptr() as *const u8, target_bytes) }
        {
            return true;
        }
    }
    false
}

/// Executes the File I/O verification test suite using the active Win32 shims.
unsafe fn run_fileio_tests() {
    use crate::pe::shims::*;
    use std::ffi::CString;

    let filename = CString::new("classicbasic_test.txt").unwrap();
    let payload = b"ClassicBasic Linux Native File I/O!";

    // [Test 1] CreateFileA (CREATE_ALWAYS) & WriteFile
    // GENERIC_WRITE = 0x40000000, CREATE_ALWAYS = 2, FILE_ATTRIBUTE_NORMAL = 0x80
    let h_write = win32_CreateFileA(
        filename.as_ptr(),
        0x40000000,
        0,
        core::ptr::null_mut(),
        2,
        0x80,
        0,
    );

    if h_write != 0xFFFFFFFF && h_write != !0usize {
        println!("[Test 1] CreateFileA (Write): Handle OK");
    } else {
        println!("[Test 1] CreateFileA (Write): Failed");
    }

    let mut bytes_written: u32 = 0;
    win32_WriteFile(
        h_write,
        payload.as_ptr(),
        payload.len() as u32,
        &mut bytes_written,
        core::ptr::null_mut(),
    );
    println!("[Test 1] WriteFile bytes: {}", bytes_written);

    // [Test 2] CloseHandle (Write)
    let close_res = win32_CloseHandle(h_write);
    println!("[Test 2] CloseHandle (Write): {}", close_res);

    // [Test 3] CreateFileA (OPEN_EXISTING) & GetFileSize
    // GENERIC_READ = 0x80000000, FILE_SHARE_READ = 1, OPEN_EXISTING = 3
    let h_read = win32_CreateFileA(
        filename.as_ptr(),
        0x80000000,
        1,
        core::ptr::null_mut(),
        3,
        0x80,
        0,
    );

    if h_read != 0xFFFFFFFF && h_read != !0usize {
        println!("[Test 3] CreateFileA (Read): Handle OK");
    } else {
        println!("[Test 3] CreateFileA (Read): Failed");
    }

    let mut size_high: u32 = 0;
    let file_size = win32_GetFileSize(h_read, &mut size_high);
    println!("[Test 3] GetFileSize: {}", file_size);

    // [Test 4] ReadFile
    let mut read_buf = vec![0u8; file_size as usize];
    let mut bytes_read: u32 = 0;
    win32_ReadFile(
        h_read,
        read_buf.as_mut_ptr(),
        file_size,
        &mut bytes_read,
        core::ptr::null_mut(),
    );
    let content = String::from_utf8_lossy(&read_buf[..bytes_read as usize]);
    println!("[Test 4] ReadFile bytes: {}", bytes_read);
    println!("[Test 4] Content: {}", content);

    win32_CloseHandle(h_read);

    // Clean up temporary test file
    let _ = std::fs::remove_file("classicbasic_test.txt");

    // [Test 5] Error Handling (Abrir arquivo inexistente)
    let missing_name = CString::new("non_existent_file_xyz.tmp").unwrap();
    let h_missing = win32_CreateFileA(
        missing_name.as_ptr(),
        0x80000000,
        0,
        core::ptr::null_mut(),
        3,
        0x80,
        0,
    );
    let display_h: i32 = if h_missing == 0xFFFFFFFF || h_missing == !0usize {
        -1
    } else {
        h_missing as i32
    };
    println!("[Test 5] Open NonExistent: {}", display_h);
}

