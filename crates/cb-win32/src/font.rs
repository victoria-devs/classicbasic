/// Returns the 8x16 bitmap glyph slice for the given ASCII byte.
pub fn get_glyph_8x16(c: u8) -> &'static [u8; 16] {
    if (32..=126).contains(&c) {
        &FONT_8X16[(c - 32) as usize]
    } else {
        // Fallback to '?' (ASCII 63)
        &FONT_8X16[(63 - 32) as usize]
    }
}
